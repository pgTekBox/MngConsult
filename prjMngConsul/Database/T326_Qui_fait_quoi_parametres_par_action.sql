--   1. Définitions et valeurs par défaut sur la compagnie modèle (+ libellés T102).
--   2. Toutes les compagnies reçoivent leurs paramètres (s0150, comme à
--      l'ouverture de Paramètres).
--   3. Le cliché des compagnies démo (DEMO_T100 / DEMO_T101) reçoit les mêmes
--      lignes : une réinitialisation de démo les garde.
-- Source : js/qui-fait-quoi-data.js (inventaire v5.2) — 448 actions.

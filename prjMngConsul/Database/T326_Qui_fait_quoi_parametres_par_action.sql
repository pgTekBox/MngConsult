-- 2. Toutes les compagnies (s0150 clone du modèle ce qui manque, valeur par défaut comprise)
DECLARE @c UNIQUEIDENTIFIER;
DECLARE @R TABLE (ParamId INT, T100Id INT, ShortName VARCHAR(100), Name NVARCHAR(200), ParamType VARCHAR(200), Categorie VARCHAR(20), Ordre INT, sVal VARCHAR(8000), iVal INT, dVal DATETIME, fVal DECIMAL(18,6));
DECLARE cur CURSOR LOCAL FAST_FORWARD FOR
    SELECT CompanyGUID FROM dbo.T010Company WHERE CompanyGUID <> '00000000-0000-0000-0000-000000000001';
OPEN cur; FETCH NEXT FROM cur INTO @c;
WHILE @@FETCH_STATUS = 0
BEGIN
    INSERT @R EXEC dbo.s0150GetParamsForCompany @CompanyGUID = @c, @Categorie = 'QUIFAITQUOI';
    FETCH NEXT FROM cur INTO @c;
END
CLOSE cur; DEALLOCATE cur;
GO

